"""E4: are the LLM breed ratings stable? Compares two rating runs that differ only in the
order the traits are listed (variant a = published ratings, variant b = reversed order).

Reports, per (breed, trait) pair: whether both runs rated it or both said unknown; and,
where both rated it, exact agreement, agreement within one point and quadratic-weighted
Cohen's kappa. Also writes the owner's spot-check sheet (20 breeds, seed 42).
No model is trained on these ratings.

Run: python -m pipeline.rating_consistency
"""

import argparse
import csv
import random
from collections import Counter
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

from pipeline.ratings import RATINGS_PATH, TRAITS, Rating, read_ratings

REPORT_PATH = Path("eval/e4_rating_consistency.md")
SPOTCHECK_PATH = Path("eval/ratings_spotcheck.csv")
SPOTCHECK_BREEDS = 20
SEED = 42


@dataclass(frozen=True)
class Agreement:
    pairs: int
    both_rated: int
    both_unknown: int
    only_a: int
    only_b: int
    exact: int
    within_one: int
    kappa: float | None

    @property
    def same_decision(self) -> int:
        """Pairs where both runs rated, or both said unknown."""
        return self.both_rated + self.both_unknown


def weighted_kappa(a: Sequence[int], b: Sequence[int], levels: int = 5) -> float | None:
    """Quadratic-weighted Cohen's kappa for two raters on a 1..levels scale."""
    n = len(a)
    if n == 0:
        return None
    observed = [[0.0] * levels for _ in range(levels)]
    for x, y in zip(a, b, strict=True):
        observed[x - 1][y - 1] += 1
    row = [sum(r) for r in observed]
    col = [sum(observed[i][j] for i in range(levels)) for j in range(levels)]
    num = den = 0.0
    for i in range(levels):
        for j in range(levels):
            weight = (i - j) ** 2 / (levels - 1) ** 2
            num += weight * observed[i][j]
            den += weight * row[i] * col[j] / n
    return 1.0 - num / den if den else None


def compare(a: Sequence[Rating], b: Sequence[Rating], trait: str | None = None) -> Agreement:
    scores_b = {(r.breed, r.trait): r.score for r in b}
    pairs = [(r, scores_b[(r.breed, r.trait)]) for r in a if trait in (None, r.trait)]
    rated = [(r.score, sb) for r, sb in pairs if r.score is not None and sb is not None]
    xs = [x for x, _ in rated if x is not None]
    ys = [y for _, y in rated if y is not None]
    return Agreement(
        pairs=len(pairs),
        both_rated=len(rated),
        both_unknown=sum(r.score is None and sb is None for r, sb in pairs),
        only_a=sum(r.score is not None and sb is None for r, sb in pairs),
        only_b=sum(r.score is None and sb is not None for r, sb in pairs),
        exact=sum(x == y for x, y in zip(xs, ys, strict=True)),
        within_one=sum(abs(x - y) <= 1 for x, y in zip(xs, ys, strict=True)),
        kappa=weighted_kappa(xs, ys),
    )


def big_disagreements(a: Sequence[Rating], b: Sequence[Rating]) -> list[tuple[Rating, int]]:
    """Pairs both runs rated but more than one point apart."""
    scores_b = {(r.breed, r.trait): r.score for r in b}
    out = []
    for r in a:
        other = scores_b[(r.breed, r.trait)]
        if r.score is not None and other is not None and abs(r.score - other) > 1:
            out.append((r, other))
    return out


def _pct(n: int, d: int) -> str:
    return f"{100 * n / d:.0f}%" if d else "-"


def _quote_validity(ratings: Sequence[Rating]) -> str:
    claimed = sum(r.status in ("rated", "quote_not_found", "quote_too_short") for r in ratings)
    return f"{sum(r.status == 'rated' for r in ratings)}/{claimed}"


def render_report(a: Sequence[Rating], b: Sequence[Rating]) -> str:
    total = compare(a, b)
    kappa = f"{total.kappa:.2f}" if total.kappa is not None else "-"
    lines = [
        "# E4: LLM rating consistency",
        "",
        "Generated by `python -m pipeline.rating_consistency`. Two runs of the same model",
        "and prompt that differ only in trait order (a: published ratings, b: reversed).",
        "No model is trained on these ratings.",
        "",
        "## Overall",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| (breed, trait) pairs | {total.pairs} |",
        f"| Rated in run a / run b | {total.both_rated + total.only_a} / "
        f"{total.both_rated + total.only_b} |",
        f"| Same rated-or-unknown decision | {_pct(total.same_decision, total.pairs)} |",
        f"| Both rated | {total.both_rated} |",
        f"| ...exact agreement | {_pct(total.exact, total.both_rated)} |",
        f"| ...within one point | {_pct(total.within_one, total.both_rated)} |",
        f"| ...quadratic-weighted kappa | {kappa} |",
        f"| Quotes verified in the article (a / b) | {_quote_validity(a)} / {_quote_validity(b)} |",
        "",
        "## Per trait",
        "",
        "| Trait | Rated a | Rated b | Both | Exact | Within 1 | Kappa |",
        "|---|---|---|---|---|---|---|",
    ]
    for trait in TRAITS:
        t = compare(a, b, trait)
        k = f"{t.kappa:.2f}" if t.kappa is not None else "-"
        lines.append(
            f"| {trait} | {t.both_rated + t.only_a} | {t.both_rated + t.only_b} | {t.both_rated} "
            f"| {_pct(t.exact, t.both_rated)} | {_pct(t.within_one, t.both_rated)} | {k} |"
        )
    lines += ["", "## Disagreements of more than one point", ""]
    big = big_disagreements(a, b)
    if big:
        lines += ["| Breed | Trait | a | b |", "|---|---|---|---|"]
        lines += [f"| {r.breed} | {r.trait} | {r.score} | {other} |" for r, other in big]
    else:
        lines.append("None.")
    return "\n".join(lines) + "\n"


def spotcheck_rows(a: Sequence[Rating], b: Sequence[Rating]) -> list[dict[str, str]]:
    """Every rated trait of 20 randomly chosen breeds (seed 42), for the owner to verify."""
    rated_breeds = sorted({r.breed for r in a if r.score is not None})
    chosen = set(random.Random(SEED).sample(rated_breeds, min(SPOTCHECK_BREEDS, len(rated_breeds))))
    scores_b = {(r.breed, r.trait): r.score for r in b}
    rows = []
    for r in a:
        if r.breed in chosen and r.score is not None:
            other = scores_b[(r.breed, r.trait)]
            rows.append(
                {
                    "breed": r.breed,
                    "trait": r.trait,
                    "score": str(r.score),
                    "score_run_b": "" if other is None else str(other),
                    "evidence": r.evidence,
                    "article": f"https://en.wikipedia.org/w/index.php?oldid={r.wikipedia_revision_id}",
                    "your_verdict": "",
                    "your_note": "",
                }
            )
    return rows


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="E4: compare two LLM rating runs.")
    parser.add_argument("--a", type=Path, default=RATINGS_PATH)
    parser.add_argument("--b", type=Path, default=Path("data/interim/ratings_b.csv"))
    args = parser.parse_args(argv)

    a, b = read_ratings(args.a), read_ratings(args.b)
    if Counter((r.breed, r.trait) for r in a) != Counter((r.breed, r.trait) for r in b):
        raise SystemExit("the two runs do not cover the same breeds and traits")
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text(render_report(a, b), encoding="utf-8", newline="\n")
    rows = spotcheck_rows(a, b)
    with SPOTCHECK_PATH.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]), lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    print(f"report: {REPORT_PATH}; spot-check sheet: {SPOTCHECK_PATH} ({len(rows)} rows)")


if __name__ == "__main__":
    main()
